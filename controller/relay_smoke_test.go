func e01NonStreamBody(t *testing.T, dbType common.DatabaseType) {
	f := setupRelaySmoke(t, dbType, relayRedisPerTest)
	ckpt := f.tracker.checkpoint()
	rec := doRequest(f, f.tokenKey, chatBody(t, false))
	require.True(t, waitUpstreamHit(f.upstreamCh, 1), "upstream must be hit exactly once")

	require.Equal(t, http.StatusOK, rec.Code, "non-stream success must be 200, body=%s", rec.Body.String())
	require.Equal(t, int64(1), f.upstreamHit.Load(), "upstream must be hit exactly once")
	body := rec.Body.String()
	assert.Contains(t, body, "chatcmpl-smoke")
	assertNoUpstreamKeyLeak(t, body, rec.Header(), nil)

	f.mu.Lock()
	mockErr := f.mockErr
	f.mu.Unlock()
	require.NoError(t, mockErr, "upstream mock must not have recorded an error")

	awaitRelayAsync(t, f, ckpt, []p10WaitRequirement{
		{Category: p10RedisCatTokenQuotaWrite, Count: 1},
		{Category: p10RedisCatUserQuotaWrite, Count: 1},
		{Category: p10RedisCatPerfWrite, Count: 1},
	})
}

