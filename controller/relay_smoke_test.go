// waitUpstreamHit waits for the upstream to observe n hits, using a timeout
// guard rather than a fixed sleep.
func waitUpstreamHit(ch <-chan struct{}, n int) bool {
	for i := 0; i < n; i++ {
		select {
		case <-ch:
		case <-time.After(5 * time.Second):
			return false
		}
	}
	return true
}

