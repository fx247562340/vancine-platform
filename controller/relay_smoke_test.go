// setupRelaySmoke stands up an isolated DB through the real production init
// chain, seeds one user + token + one OpenAI-compatible channel + ability
// pointing at the local upstream, and exposes a real router through
// TokenAuth -> ModelRequestRateLimit -> Distribute -> Relay. The token is
// finite-quota (UnlimitedQuota=false) so pre-consume / settle / refund token
// state is precisely observable.
func setupRelaySmoke(t *testing.T, dbType common.DatabaseType, redisMode relayRedisMode) *relaySmokeFixture {
	t.Helper()
	require.NoError(t, i18n.Init())
	p10SetupDatabase(t, dbType,
		&model.User{}, &model.Token{}, &model.Channel{}, &model.Log{},
		&model.Ability{}, &model.Model{}, &model.UserSession{},
		&model.UserSubscription{}, &model.SubscriptionOrder{}, &model.SubscriptionPreConsumeRecord{},
		&model.Option{}, &model.Redemption{}, &model.QuotaData{},
	)

	// Use miniredis to provide a real in-process Redis instance. The
	// telemetry goroutine's Redis calls go to miniredis (safe, in-memory),
	// and the cleanup restores the previous Redis globals after the miniredis
	// client is closed. This eliminates the cross-test write-vs-read race
	// that occurred when RedisEnabled was set false and never restored.
	// The p10RedisTracker hook records all Redis commands with sanitized
	// category classification so tests can wait for specific async task
	// types (token-cache, rate-limit, performance) without exposing sensitive keys.
	//
	// For E07 (rate limiter), the shared p10SharedRedisClient is used because
	// the limiter.New singleton (sync.Once) permanently saves the first client
	// it receives. The shared client lives for the entire process and is only
	// closed in TestMain. For all other tests, a per-test miniredis is created.
	prevRedisEnabled := common.RedisEnabled
	prevRDB := common.RDB
	var redisClient *redis.Client
	var tracker *p10RedisTracker
	sharedRedis := redisMode == relayRedisSharedRateLimiter
	if sharedRedis {
		// E07 mode: use the shared client and shared tracker. The shared
		// client's single permanent hook is the shared tracker. No per-test
		// hook accumulation.
		redisClient = p10SharedRedisClient
		tracker = p10SharedTracker
	} else {
		// Default mode: per-test miniredis with per-test tracker.
		redisServer := miniredis.RunT(t)
		redisClient = redis.NewClient(&redis.Options{Addr: redisServer.Addr()})
		require.NoError(t, redisClient.Ping(context.Background()).Err())
		tracker = newP10RedisTracker()
		redisClient.AddHook(tracker)
	}
	require.NoError(t, redisClient.Ping(context.Background()).Err())
	common.RedisEnabled = true
	common.RDB = redisClient
	t.Cleanup(func() {
		// Restore globals FIRST, then close the per-test client. This
		// ensures no goroutine reads common.RDB after the client is closed.
		common.RedisEnabled = prevRedisEnabled
		common.RDB = prevRDB
		// Only close per-test clients. The shared client is closed in TestMain.
		if !sharedRedis {
			assert.NoError(t, redisClient.Close(), "redis client close must succeed")
		}
	})

	prevMemoryCache := common.MemoryCacheEnabled
	common.MemoryCacheEnabled = false
	t.Cleanup(func() { common.MemoryCacheEnabled = prevMemoryCache })

	prevGroupRatio := common.TopupGroupRatio2JSONString()
	require.NoError(t, common.UpdateTopupGroupRatioByJSONString(`{"default":1}`))
	t.Cleanup(func() {
		if err := common.UpdateTopupGroupRatioByJSONString(prevGroupRatio); err != nil {
			t.Errorf("restore group ratio: %v", err)
		}
	})

	prevModelRatio := ratio_setting.GetModelRatioCopy()
	require.NoError(t, ratio_setting.UpdateModelRatioByJSONString(
		`{"`+relaySmokeModel+`": 2.5}`))
	t.Cleanup(func() {
		if b, err := common.Marshal(prevModelRatio); err == nil {
			if err := ratio_setting.UpdateModelRatioByJSONString(string(b)); err != nil {
				t.Errorf("restore model ratio: %v", err)
			}
		}
	})

	prevStreamingTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 300
	t.Cleanup(func() { constant.StreamingTimeout = prevStreamingTimeout })

	// common.Init() is not called in tests, so common.SyncFrequency defaults
	// to 0. Billing cache writes (cacheIncrUserQuota / cacheIncrTokenQuota)
	// check the cache key's TTL > 0 before calling HINCRBY. If SyncFrequency
	// is 0, the auth-path cache write (cacheSetToken / cacheSetUser) sets no
	// TTL, so the billing HINCRBY is silently skipped. Setting SyncFrequency
	// to 60 (the production default) ensures cache keys get a TTL and billing
	// writes actually reach Redis.
	prevSyncFrequency := common.SyncFrequency
	common.SyncFrequency = 60
	t.Cleanup(func() { common.SyncFrequency = prevSyncFrequency })

	// Use a deterministic atomic counter for IDs so SQLite and PG fixtures
	// produce the same IDs (no time.Now() dependency).
	smokeSeqMu.Lock()
	smokeSeq++
	userID := smokeSeq*1000 + 1
	channelID := smokeSeq*1000 + 2
	tokenID := smokeSeq*1000 + 3
	smokeSeqMu.Unlock()
	// TokenAuth extracts the key as the part before the first "-". Use a bare
	// alphanumeric key with no dash so parts[0] equals the full token key.
	tokenKey := common.GetRandomString(32)

	user := &model.User{
		Id:          userID,
		Username:    fmt.Sprintf("smoke-%d", userID),
		Password:    "ignored",
		Role:        common.RoleCommonUser,
		Status:      common.UserStatusEnabled,
		Group:       "default",
		AffCode:     fmt.Sprintf("smoke-%d", userID),
		AuthVersion: 1,
		Quota:       relaySmokeStartQuota,
	}
	require.NoError(t, model.DB.Create(user).Error)

	token := &model.Token{
		Id:             tokenID,
		UserId:         userID,
		Key:            tokenKey,
		Name:           "smoke-token",
		Status:         common.TokenStatusEnabled,
		ExpiredTime:    -1, // never expires
		RemainQuota:    relaySmokeTokenQuota,
		UnlimitedQuota: false,
		Group:          "default",
		CreatedTime:    time.Now().Unix(),
		AccessedTime:   time.Now().Unix(),
	}
	require.NoError(t, model.DB.Create(token).Error)
	priority := int64(1)
	emptyStr := ""
	channel := &model.Channel{
		Id:       channelID,
		Name:     "smoke-channel",
		Type:     constant.ChannelTypeOpenAI,
		Status:   common.ChannelStatusEnabled,
		Key:      relaySmokeUpstreamKey,
		BaseURL:  &emptyStr, // patched in after upstream URL is known
		Group:    "default",
		Priority: &priority,
	}
	require.NoError(t, model.DB.Create(channel).Error)

	ability := &model.Ability{
		Group:     "default",
		Model:     relaySmokeModel,
		ChannelId: channelID,
		Enabled:   true,
		Priority:  &priority,
		Weight:    10,
	}
	require.NoError(t, model.DB.Create(ability).Error)

	upstreamCh := make(chan struct{}, 1024)
	f := &relaySmokeFixture{
		upstreamCh: upstreamCh,
		tracker:    tracker,
		userID:     userID,
		tokenID:    tokenID,
		tokenKey:   tokenKey,
		channelID:  channelID,
	}

	// The upstream mock only records a hit, the auth header, and any read or
	// write error into the fixture; it never touches testing.T.
	upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		f.upstreamHit.Add(1)
		select {
		case f.upstreamCh <- struct{}{}:
		default:
		}
		f.mu.Lock()
		f.lastAuthHeader = r.Header.Get("Authorization")
		f.mu.Unlock()
		body, err := io.ReadAll(r.Body)
		if err != nil {
			f.mu.Lock()
			f.mockErr = err
			f.mu.Unlock()
			w.WriteHeader(http.StatusInternalServerError)
			return
		}
		_ = body
		w.Header().Set("Content-Type", "application/json")
		w.Header().Set("x-request-id", "smoke-upstream")
		w.WriteHeader(http.StatusOK)
		if _, err := w.Write(successBody()); err != nil {
			f.mu.Lock()
			f.mockErr = err
			f.mu.Unlock()
		}
	}))
	f.upstream = upstream
	t.Cleanup(upstream.Close)

	require.NoError(t, model.DB.Model(&model.Channel{}).
		Where("id = ?", channelID).
		Update("base_url", upstream.URL+"/v1").Error)

	f.router = gin.New()
	relayGroup := f.router.Group("/v1")
	relayGroup.Use(middleware.TokenAuth())
	relayGroup.Use(middleware.ModelRequestRateLimit())
	relayGroup.Use(middleware.Distribute())
	relayGroup.POST("/chat/completions", func(c *gin.Context) {
		ctx := context.WithValue(c.Request.Context(), smokeFixtureKey{}, f)
		c.Request = c.Request.WithContext(ctx)
		Relay(c, types.RelayFormatOpenAI)
	})

	return f
}

