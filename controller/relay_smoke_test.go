// refundBarrier provides a deterministic wait for the asynchronous
// BillingSession.Refund writes (user quota restore + token quota restore)
// so the test never tears down the DB while the gopool goroutine is still
// writing. It uses GORM after-update callbacks on the users and tokens
// tables; the callback only sends to a buffered channel and never touches
// testing.T. The barrier verifies persistent state after each event rather
// than draining-then-assuming: each DB-update event triggers a re-read of
// user quota, token remain, and token used; the barrier succeeds only when
// ALL three match the expected final values. A timeout is a failure guard,
// not a success criterion.
type refundBarrier struct {
	userSig    chan struct{}
	tokenSig   chan struct{}
	expectQ    int // expected final user quota
	expectRem  int // expected final token remain
	expectUsed int // expected final token used
	userID     int
}

const (
	refundBarrierUserCallback  = "test:refund_barrier_user_v2"
	refundBarrierTokenCallback = "test:refund_barrier_token_v2"
)

// installRefundBarrier registers unique after-update callbacks on the users
// and tokens tables, scoped to the given user ID. The barrier succeeds
// only when the persisted user quota, token remain, and token used all
// match the expected final values.
func installRefundBarrier(t *testing.T, userID, expectQ, expectRem, expectUsed int) *refundBarrier {
	t.Helper()
	b := &refundBarrier{
		userSig:    make(chan struct{}, 16),
		tokenSig:   make(chan struct{}, 16),
		expectQ:    expectQ,
		expectRem:  expectRem,
		expectUsed: expectUsed,
		userID:     userID,
	}
	require.NoError(t, model.DB.Callback().Update().After("gorm:update").
		Register(refundBarrierUserCallback, func(tx *gorm.DB) {
			if tx.Statement.Table == "users" {
				select {
				case b.userSig <- struct{}{}:
				default:
				}
			}
		}))
	require.NoError(t, model.DB.Callback().Update().After("gorm:update").
		Register(refundBarrierTokenCallback, func(tx *gorm.DB) {
			if tx.Statement.Table == "tokens" {
				select {
				case b.tokenSig <- struct{}{}:
				default:
				}
			}
		}))
	t.Cleanup(func() {
		assert.NoError(t, model.DB.Callback().Update().Remove(refundBarrierUserCallback),
			"refund barrier user callback cleanup must succeed")
		assert.NoError(t, model.DB.Callback().Update().Remove(refundBarrierTokenCallback),
			"refund barrier token callback cleanup must succeed")
	})
	return b
}

// waitForRefund consumes DB-update events and checks persistent state after
// each one. It returns when the persisted user quota, token remain, and token
// used all match the expected final values. The timeout is a failure guard,
// not a success criterion: if the refund has already completed before
// waitForRefund is called, the channel buffer still contains the event(s)
// and the state check succeeds on the first read.
func (b *refundBarrier) waitForRefund(t *testing.T) {
	t.Helper()
	deadline := time.After(5 * time.Second)
	for {
		select {
		case <-b.userSig:
			if b.checkState(t) {
				return
			}
		case <-b.tokenSig:
			if b.checkState(t) {
				return
			}
		case <-deadline:
			// Timeout unconditionally fails: the refund's DB-update signal
			// must have been observed. A final state re-read that happens
			// to match does NOT count as success — only a real user/token
			// update signal that persists to the expected final values
			// proves the refund completed.
			require.Fail(t, "refund barrier: persistent state did not reach expected values within 5s (no update signal observed)")
		}
	}
}

// checkState reads the persisted user quota, token remain, and token used
// and returns true only when all three match the expected final values.
func (b *refundBarrier) checkState(t *testing.T) bool {
	t.Helper()
	var q int
	if err := model.DB.Model(&model.User{}).Where("id = ?", b.userID).Select("quota").Scan(&q).Error; err != nil {
		return false
	}
	var rem, used int
	if err := model.DB.Model(&model.Token{}).Where("user_id = ?", b.userID).Select("remain_quota").Scan(&rem).Error; err != nil {
		return false
	}
	if err := model.DB.Model(&model.Token{}).Where("user_id = ?", b.userID).Select("used_quota").Scan(&used).Error; err != nil {
		return false
	}
	return q == b.expectQ && rem == b.expectRem && used == b.expectUsed
}

// assertNoUpstreamKeyLeak checks that the sentinel never appears in a body,
// any header value, or a persisted log.
func assertNoUpstreamKeyLeak(t *testing.T, body string, header http.Header, logs []model.Log) {
	t.Helper()
	assert.NotContains(t, body, relaySmokeUpstreamKey, "response body leaks upstream key")
	for k, vs := range header {
		for _, v := range vs {
			assert.NotContains(t, v, relaySmokeUpstreamKey, "header %q leaks upstream key", k)
		}
	}
	for _, l := range logs {
		assert.NotContains(t, l.Content, relaySmokeUpstreamKey, "log content leaks upstream key")
		assert.NotContains(t, l.Other, relaySmokeUpstreamKey, "log other leaks upstream key")
	}
}

// awaitRelayAsync is a stable business-concept helper: it captures a
// tracker checkpoint before a relay request, then after the request
// completes (and any worker has joined), waits for the expected async
// Redis events and asserts no non-redis.Nil errors occurred after the
// checkpoint. Only WRITE categories satisfy settlement/refund/telemetry
// waits; read categories are used for auth-path queries. Common patterns:
//   - successful relay: token-write, user-write, perf-write
//   - failed relay (refund): token-write, user-write, perf-write
//   - rate-limit first request: rate-limit, token-write, user-write, perf-write
//   - rate-limit second request: rate-limit (only)
//   - E03 rejection: (empty — no billing events expected)
//
// snapshotAfter returns a one-shot snapshot of events after the given
// checkpoint. It does not use a timer, sleep, or polling — it is an
// instantaneous read of the current ledger state.
func snapshotAfter(f *relaySmokeFixture, ckpt int64) []p10RedisEvent {
	f.tracker.mu.Lock()
	defer f.tracker.mu.Unlock()
	var matched []p10RedisEvent
	for _, evt := range f.tracker.events {
		if evt.Seq > ckpt {
			matched = append(matched, evt)
		}
	}
	return matched
}

// assertNoBillingWrites asserts that the given snapshot contains no
// billing/quota mutation events (token-quota-write, user-quota-write,
// perf-write). Auth-cache writes (token-cache-write, user-cache-write)
// are allowed — they are synchronous auth-path cache updates, not billing.
func assertNoBillingWrites(t *testing.T, snapshot []p10RedisEvent) {
	t.Helper()
	for _, evt := range snapshot {
		for _, bc := range p10BillingQuotaCategories {
			if evt.Category == bc {
				t.Errorf("no billing mutation expected after checkpoint, got category=%q cmd=%q", evt.Category, evt.Cmd)
			}
		}
	}
}

// awaitRelayAsync is a stable business-concept helper: it captures a
// tracker checkpoint before a relay request, then after the request
// completes (and any worker has joined), waits for the expected async
// Redis events and asserts no non-redis.Nil errors occurred after the
// checkpoint. Only WRITE categories satisfy settlement/refund/telemetry
// waits. When reqs is nil/empty the caller should use snapshotAfter +
// assertNoBillingWrites instead.
func awaitRelayAsync(t *testing.T, f *relaySmokeFixture, ckpt int64, reqs []p10WaitRequirement) {
	t.Helper()
	require.NotEmpty(t, reqs, "use snapshotAfter + assertNoBillingWrites for no-event assertions")
	result := f.tracker.waitAfter(ckpt, reqs, 5*time.Second)
	require.False(t, result.TimedOut,
		"async events not observed within 5s: wanted %v, got %d matched", reqs, len(result.Matched))
	require.Empty(t, result.Errors,
		"no non-redis.Nil errors expected after checkpoint, got %v", result.Errors)
}

