func TestRelaySmokeE07_RateLimitBlocksSecondRequest(t *testing.T) {
	p10RunAcrossDatabases(t, "E07", e07RateLimitBody)
}

func e07RateLimitBody(t *testing.T, dbType common.DatabaseType) {
	// E07 uses the shared Redis client because the limiter.New singleton
	// (sync.Once) permanently saves the first *redis.Client it receives.
	// The shared client lives for the entire process and is only closed
	// in TestMain.
	f := setupRelaySmoke(t, dbType, relayRedisSharedRateLimiter)

	// Save and restore the model request rate-limit globals.
	prevEnabled := setting.ModelRequestRateLimitEnabled
	prevDuration := setting.ModelRequestRateLimitDurationMinutes
	prevCount := setting.ModelRequestRateLimitCount
	prevSuccess := setting.ModelRequestRateLimitSuccessCount
	prevGroup := setting.ModelRequestRateLimitGroup2JSONString()
	t.Cleanup(func() {
		setting.ModelRequestRateLimitEnabled = prevEnabled
		setting.ModelRequestRateLimitDurationMinutes = prevDuration
		setting.ModelRequestRateLimitCount = prevCount
		setting.ModelRequestRateLimitSuccessCount = prevSuccess
		if err := setting.UpdateModelRequestRateLimitGroupByJSONString(prevGroup); err != nil {
			t.Errorf("restore rate limit group: %v", err)
		}
	})

	// Deterministic Redis rate limit: allow 1 total request in a 1-minute
	// window, so the first request is allowed and the second is rejected
	// with exactly 429 before any billing. The rate limiter middleware
	// checks common.RedisEnabled and uses common.RDB (the miniredis
	// instance created by setupRelaySmoke).
	setting.ModelRequestRateLimitEnabled = true
	setting.ModelRequestRateLimitDurationMinutes = 1
	setting.ModelRequestRateLimitCount = 1
	setting.ModelRequestRateLimitSuccessCount = 1000
	require.NoError(t, setting.UpdateModelRequestRateLimitGroupByJSONString(`{}`))

	// Deterministic user identity (isolated from other tests).
	ckpt := f.tracker.checkpoint()
	first := doRequest(f, f.tokenKey, chatBody(t, false))
	require.True(t, waitUpstreamHit(f.upstreamCh, 1), "first request must reach upstream")
	require.Equal(t, http.StatusOK, first.Code, "first request must be 2xx, body=%s", first.Body.String())
	assert.Equal(t, int64(1), f.upstreamHit.Load(), "first request hits upstream once")
	assert.Equal(t, relaySmokeFinalUserQuota, readUserQuota(t, f.userID), "first request settles exactly 25")
	assert.Equal(t, int64(1), countUserLogs(t, f.userID), "first request writes exactly one log")

	// Wait for first request's async Redis events (rate-limit, token-cache,
	// user-cache, performance) before issuing the second request.
	awaitRelayAsync(t, f, ckpt, []p10WaitRequirement{
		{Category: p10RedisCatRateLimitWrite, Count: 1},
		{Category: p10RedisCatTokenQuotaWrite, Count: 1},
		{Category: p10RedisCatUserQuotaWrite, Count: 1},
		{Category: p10RedisCatPerfWrite, Count: 1},
	})

	// Second request: rate-limited. Uses its own checkpoint.
	ckpt2 := f.tracker.checkpoint()
	second := doRequest(f, f.tokenKey, chatBody(t, false))
	require.Equal(t, http.StatusTooManyRequests, second.Code,
		"second request must be exactly 429, got %d", second.Code)
	assert.Equal(t, int64(1), f.upstreamHit.Load(),
		"second request must not reach the upstream (hit stays 1)")
	assert.Equal(t, relaySmokeFinalUserQuota, readUserQuota(t, f.userID),
		"second request must not change user quota")
	remain, used := readTokenQuota(t, f.userID)
	assert.Equal(t, relaySmokeTokenQuota-relaySmokeExpectedCost, remain,
		"second request must not change token remain")
	assert.Equal(t, relaySmokeExpectedCost, used, "second request must not change token used")
	assert.Equal(t, int64(1), countUserLogs(t, f.userID),
		"second request must not add a consume log")

	// Wait for the rate-limit-write event from the 429 path, then snapshot
	// the ledger and assert no billing writes (user-write, perf-write,
	// token-write) occurred.
	awaitRelayAsync(t, f, ckpt2, []p10WaitRequirement{
		{Category: p10RedisCatRateLimitWrite, Count: 1},
	})
	snap := snapshotAfter(f, ckpt2)
	assertNoBillingWrites(t, snap)
}

