// --- E03 missing / invalid / disabled token, no state change ---

func TestRelaySmokeE03_TokenRejectionBlocksUpstream(t *testing.T) {
	p10RunAcrossDatabases(t, "E03", e03TokenRejectionBody)
}

func e03TokenRejectionBody(t *testing.T, dbType common.DatabaseType) {
	f := setupRelaySmoke(t, dbType, relayRedisPerTest)

	// Record the persistent state snapshot BEFORE the first request so
	// the "unchanged" assertions are against a clean baseline.
	userQuotaBefore := readUserQuota(t, f.userID)
	tokenRemainBefore, tokenUsedBefore := readTokenQuota(t, f.userID)
	logsBefore := countUserLogs(t, f.userID)
	hitsBefore := f.upstreamHit.Load()

	requestBody := chatBody(t, false)

	// Missing and invalid token requests never reach the relay handler,
	// so no auth-cache writes occur.
	cases := []struct {
		name string
		key  string
	}{
		{name: "missing token", key: ""},
		{name: "invalid token", key: "definitely-not-a-real-key"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			ckpt := f.tracker.checkpoint()
			rec := doRequest(f, tc.key, requestBody)
			require.True(t, rec.Code == http.StatusUnauthorized || rec.Code == http.StatusForbidden,
				"must be 401/403, got %d", rec.Code)
			assert.Equal(t, hitsBefore, f.upstreamHit.Load(), "upstream hit delta must be 0")
			assert.Equal(t, userQuotaBefore, readUserQuota(t, f.userID), "user quota unchanged")
			remain, used := readTokenQuota(t, f.userID)
			assert.Equal(t, tokenRemainBefore, remain, "token remain unchanged")
			assert.Equal(t, tokenUsedBefore, used, "token used unchanged")
			assert.Equal(t, logsBefore, countUserLogs(t, f.userID), "consume log count unchanged")
			snap := snapshotAfter(f, ckpt)
			assertNoBillingWrites(t, snap)
		})
	}

	// Disabled token: disable the token in the DB directly (not via a shared
	// token struct, which races with gopool goroutines from the pre-warm
	// path). Then make the request and assert rejection. The auth-path
	// cache write (from GetTokenByKey during the rejected request) is a
	// synchronous read followed by a cache-set, NOT a settlement event.
	t.Run("disabled token", func(t *testing.T) {
		// Direct DB update avoids sharing a token struct with gopool
		// goroutines from GetTokenByKey/cacheSetToken.
		require.NoError(t, model.DB.Model(&model.Token{}).
			Where("user_id = ?", f.userID).
			Update("status", common.TokenStatusDisabled).Error,
			"DB update must succeed")
		t.Cleanup(func() {
			assert.NoError(t,
				model.DB.Model(&model.Token{}).
					Where("user_id = ?", f.userID).
					Update("status", common.TokenStatusEnabled).Error,
				"token restore must succeed")
		})

		// Checkpoint before the request so the auth-path cache write
		// (gopool cacheSetToken after DB read) is captured.
		ckpt := f.tracker.checkpoint()
		rec := doRequest(f, f.tokenKey, requestBody)
		require.True(t, rec.Code == http.StatusUnauthorized || rec.Code == http.StatusForbidden,
			"disabled token must be 401/403, got %d", rec.Code)
		assert.Equal(t, hitsBefore, f.upstreamHit.Load(), "upstream hit delta must be 0")
		assert.Equal(t, userQuotaBefore, readUserQuota(t, f.userID), "user quota unchanged")
		remain, used := readTokenQuota(t, f.userID)
		assert.Equal(t, tokenRemainBefore, remain, "token remain unchanged")
		assert.Equal(t, tokenUsedBefore, used, "token used unchanged")
		assert.Equal(t, logsBefore, countUserLogs(t, f.userID), "consume log count unchanged")

		// Wait for the auth-path cache write (gopool cacheSetToken) to
		// complete. This is a token-cache-write, NOT a billing mutation.
		awaitRelayAsync(t, f, ckpt, []p10WaitRequirement{
			{Category: p10RedisCatTokenCacheWrite, Count: 1},
		})

		// Snapshot and assert no billing mutations (token-quota-write,
		// user-quota-write, perf-write). Auth-cache writes are allowed.
		snap := snapshotAfter(f, ckpt)
		assertNoBillingWrites(t, snap)
	})
}

// --- E04 upstream 5xx, refund completes deterministically ---

func TestRelaySmokeE04_Upstream5xxSurfacesCleanError(t *testing.T) {
	p10RunAcrossDatabases(t, "E04", e04Upstream5xxBody)
}

func e04Upstream5xxBody(t *testing.T, dbType common.DatabaseType) {
	f := setupRelaySmoke(t, dbType, relayRedisPerTest)
	preCkpt := f.tracker.checkpoint()
	startUserQ := readUserQuota(t, f.userID)
	startRemain, _ := readTokenQuota(t, f.userID)

	// Swap upstream to a 5xx responder with ready/release barrier.
	f.upstream.Close()
	readyCh := make(chan struct{}, 1)
	releaseCh := make(chan struct{})
	var releaseOnce sync.Once
	var upstreamWriteErr error
	var writeErrMu sync.Mutex
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		f.upstreamHit.Add(1)
		select {
		case readyCh <- struct{}{}:
		default:
		}
		<-releaseCh
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusInternalServerError)
		if _, err := w.Write([]byte(`{"error":"upstream unavailable"}`)); err != nil {
			writeErrMu.Lock()
			upstreamWriteErr = err
			writeErrMu.Unlock()
		}
	}))
	f.upstream = srv
	t.Cleanup(srv.Close)
	require.NoError(t, model.DB.Model(&model.Channel{}).
		Where("id = ?", f.channelID).
		Update("base_url", srv.URL+"/v1").Error)

	// Install refund barrier BEFORE the request goroutine starts.
	barrier := installRefundBarrier(t, f.userID, relaySmokeStartQuota, relaySmokeTokenQuota, 0)

	// Pre-generate request body in main goroutine.
	requestBody := chatBody(t, false)

	// Launch worker; register failure-safe defer immediately.
	readyOK := true
	recCh := make(chan *httptest.ResponseRecorder, 1)
	cbDone := make(chan struct{})
	go func() {
		defer close(cbDone)
		rec := doRequest(f, f.tokenKey, requestBody)
		recCh <- rec
	}()
	defer func() {
		releaseOnce.Do(func() { close(releaseCh) })
		<-cbDone
	}()

	// Wait for upstream to be reached.
	select {
	case <-readyCh:
	case <-time.After(5 * time.Second):
		readyOK = false
	}

	if !readyOK {
		require.Fail(t, "upstream handler did not signal ready within 5s")
	}

	// While upstream is blocked, read persistent state to prove pre-consume
	// happened (DB writes from DecreaseUserQuota/DecreaseTokenQuota).
	midUserQ := readUserQuota(t, f.userID)
	midTokenRemain, midTokenUsed := readTokenQuota(t, f.userID)
	userDelta := startUserQ - midUserQ
	tokenRemainDelta := startRemain - midTokenRemain
	assert.Greater(t, userDelta, 0, "user quota must decrease during pre-consume")
	assert.Equal(t, userDelta, tokenRemainDelta,
		"user quota delta (%d) must equal token remain delta (%d)", userDelta, tokenRemainDelta)
	assert.Equal(t, userDelta, midTokenUsed,
		"user quota delta (%d) must equal token used (%d)", userDelta, midTokenUsed)

	// Phase D: from pre-request checkpoint, wait for the pre-consume
	// billing goroutine to write user-quota-write and token-quota-write.
	// These are the HINCRBY calls from cacheIncrUserQuota/cacheIncrTokenQuota
	// in service/billing_session.go → model.IncreaseUserQuota/IncreaseTokenQuota.
	awaitRelayAsync(t, f, preCkpt, []p10WaitRequirement{
		{Category: p10RedisCatUserQuotaWrite, Count: 1},
		{Category: p10RedisCatTokenQuotaWrite, Count: 1},
	})

	// Phase E: refund checkpoint — AFTER pre-consume writes confirmed,
	// BEFORE upstream release. This cleanly separates pre-consume writes
	// from refund writes.
	refundCkpt := f.tracker.checkpoint()

	// Phase F: release upstream and join the request worker.
	releaseOnce.Do(func() { close(releaseCh) })
	<-cbDone

	// Assert 5xx response.
	rec := <-recCh
	require.Equal(t, int64(1), f.upstreamHit.Load(), "upstream hit must be exactly 1")
	writeErrMu.Lock()
	writeErrCopy := upstreamWriteErr
	writeErrMu.Unlock()
	require.NoError(t, writeErrCopy, "upstream write error must be nil")
	require.Equal(t, http.StatusInternalServerError, rec.Code,
		"upstream 5xx must surface as 5xx, body=%s", rec.Body.String())
	body := rec.Body.String()
	assert.True(t, strings.HasPrefix(strings.TrimSpace(body), "{") || strings.Contains(body, "error"),
		"upstream 5xx body must be JSON-shaped")
	assertNoUpstreamKeyLeak(t, body, rec.Header(), nil)

	// Phase G: wait for refund barrier — persistent state must reach final values.
	barrier.waitForRefund(t)

	assert.Equal(t, relaySmokeStartQuota, readUserQuota(t, f.userID),
		"user quota must be restored to start after refund")
	remain, used := readTokenQuota(t, f.userID)
	assert.Equal(t, relaySmokeTokenQuota, remain, "token remain restored")
	assert.Equal(t, 0, used, "token used restored to 0")
	assert.Equal(t, int64(0), countUserLogs(t, f.userID), "consume log delta must be 0 on failure")

	// Phase H: from refund checkpoint, wait for the refund billing goroutine
	// to write user-quota-write, token-quota-write, and perf-write. These
	// are the refund-path HINCRBY calls (IncreaseUserQuota/IncreaseTokenQuota)
	// and the perfmetrics telemetry HINCRBY.
	awaitRelayAsync(t, f, refundCkpt, []p10WaitRequirement{
		{Category: p10RedisCatUserQuotaWrite, Count: 1},
		{Category: p10RedisCatTokenQuotaWrite, Count: 1},
		{Category: p10RedisCatPerfWrite, Count: 1},
	})
}

// --- E05 quota pre-consume + settle exact ---

func TestRelaySmokeE05_QuotaPreConsumeAndSettle(t *testing.T) {
	p10RunAcrossDatabases(t, "E05", e05QuotaBody)
}

// e05Snapshot is sent by the upstream handler to the main goroutine after
// reading user/token persistent state. The handler does not call testing.T;
// it records the snapshot and any DB read error.
type e05Snapshot struct {
	userQ     int
	tokenRem  int
	tokenUsed int
	dbErr     error
	writeErr  error
}

func e05QuotaBody(t *testing.T, dbType common.DatabaseType) {
	f := setupRelaySmoke(t, dbType, relayRedisPerTest)
	ckpt := f.tracker.checkpoint()

	// Handler reads user/token persistent state and sends a structured
	// snapshot to the main goroutine. No testing.T in the handler.
	snapshotCh := make(chan e05Snapshot, 4)
	f.upstream.Close()
	okBody := successBody()
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		f.upstreamHit.Add(1)
		var snap e05Snapshot
		snap.dbErr = model.DB.Model(&model.User{}).
			Where("id = ?", f.userID).Select("quota").Scan(&snap.userQ).Error
		if snap.dbErr == nil {
			snap.dbErr = model.DB.Model(&model.Token{}).
				Where("id = ?", f.tokenID).Select("remain_quota").Scan(&snap.tokenRem).Error
		}
		if snap.dbErr == nil {
			snap.dbErr = model.DB.Model(&model.Token{}).
				Where("id = ?", f.tokenID).Select("used_quota").Scan(&snap.tokenUsed).Error
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusOK)
		if _, err := w.Write(okBody); err != nil {
			snap.writeErr = err
		}
		select {
		case snapshotCh <- snap:
		default:
		}
	}))
	f.upstream = srv
	t.Cleanup(srv.Close)
	require.NoError(t, model.DB.Model(&model.Channel{}).
		Where("id = ?", f.channelID).
		Update("base_url", srv.URL+"/v1").Error)

	rec := doRequest(f, f.tokenKey, chatBody(t, false))
	require.Equal(t, http.StatusOK, rec.Code, "success must be 200, body=%s", rec.Body.String())
	require.Equal(t, int64(1), f.upstreamHit.Load(), "upstream hit must be exactly 1")

	// Read the handler's snapshot: user/token must be in pre-consume state.
	select {
	case snap := <-snapshotCh:
		require.NoError(t, snap.dbErr, "handler DB read must succeed")
		require.NoError(t, snap.writeErr, "handler write must succeed")
		assert.Less(t, snap.userQ, relaySmokeStartQuota,
			"user quota must be lower than start during pre-consume (snapshot: %d)", snap.userQ)
		assert.Less(t, snap.tokenRem, relaySmokeTokenQuota,
			"token remain must be lower than start during pre-consume (snapshot: %d)", snap.tokenRem)
		assert.Greater(t, snap.tokenUsed, 0,
			"token used must be positive during pre-consume (snapshot: %d)", snap.tokenUsed)
		// All three deltas must be consistent (same pre-consume).
		userDelta := relaySmokeStartQuota - snap.userQ
		tokenDelta := relaySmokeTokenQuota - snap.tokenRem
		assert.Equal(t, userDelta, tokenDelta,
			"user quota delta (%d) must equal token remain delta (%d)", userDelta, tokenDelta)
		assert.Equal(t, userDelta, snap.tokenUsed,
			"user quota delta (%d) must equal token used (%d)", userDelta, snap.tokenUsed)
	case <-time.After(5 * time.Second):
		require.Fail(t, "handler snapshot not received within 5s")
	}

	// After settle, final values must be exact.
	assert.Equal(t, relaySmokeFinalUserQuota, readUserQuota(t, f.userID),
		"settled user quota must be exactly %d", relaySmokeFinalUserQuota)
	remain, used := readTokenQuota(t, f.userID)
	assert.Equal(t, relaySmokeTokenQuota-relaySmokeExpectedCost, remain,
		"token remain must reflect final consumption")
	assert.Equal(t, relaySmokeExpectedCost, used, "token used must reflect final consumption")

	awaitRelayAsync(t, f, ckpt, []p10WaitRequirement{
		{Category: p10RedisCatTokenQuotaWrite, Count: 1},
		{Category: p10RedisCatUserQuotaWrite, Count: 1},
		{Category: p10RedisCatPerfWrite, Count: 1},
	})
}

